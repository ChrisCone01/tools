import base64, json, os, glob, re, io
from PIL import Image, features

SRC = r"F:\BaiduSyncdisk\Chris\2026\0128二十四小时\0821park\素材\logo"
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "logos.js")

# 文件名以 1/2/3 结尾的 png，例如 莫离3.png
PATTERN = re.compile(r"^(?P<base>.+?)(?P<variant>[123])$")

# 裁剪框 840x680，logo 最大也就铺满框宽，超过这个尺寸纯属浪费体积
MAX_DIM = 1200

# 内嵌用 webp（带 alpha，体积约为 png 的四成）；不支持时回退 png
USE_WEBP = features.check("webp")
WEBP_QUALITY = 92

# 平均亮度高于这个值就算“浅色版”，缩略图要配深底才看得见
LIGHT_THRESHOLD = 195

try:
    import numpy as np
    HAVE_NUMPY = True
except ImportError:
    HAVE_NUMPY = False


def downscale(im, target):
    """按 alpha 预乘后缩放，避免半透明边缘出现灰边。"""
    w, h = im.size
    s = target / max(w, h)
    nw, nh = max(1, round(w * s)), max(1, round(h * s))
    if not HAVE_NUMPY:
        return im.resize((nw, nh), Image.LANCZOS)
    a = np.asarray(im, dtype=np.float64)
    al = a[..., 3:4] / 255.0
    pre = np.concatenate([a[..., :3] * al, a[..., 3:4]], axis=2)
    sm = np.asarray(
        Image.fromarray(np.clip(pre, 0, 255).astype(np.uint8), "RGBA")
             .resize((nw, nh), Image.LANCZOS), dtype=np.float64)
    sa = sm[..., 3:4] / 255.0
    rgb = np.divide(sm[..., :3], sa, out=np.zeros_like(sm[..., :3]), where=sa > 0)
    return Image.fromarray(
        np.concatenate([np.clip(rgb, 0, 255), sm[..., 3:4]], axis=2).astype(np.uint8), "RGBA")


def mean_luma(im):
    """不透明像素的平均亮度，用来决定缩略图配浅底还是深底。"""
    if HAVE_NUMPY:
        a = np.asarray(im, dtype=np.float64)
        m = a[..., 3] > 128
        if not m.any():
            return 128.0
        px = a[..., :3][m]
        return float((px[:, 0] * 0.299 + px[:, 1] * 0.587 + px[:, 2] * 0.114).mean())
    px = [p for p in im.get_flattened_data() if p[3] > 128]
    if not px:
        return 128.0
    return sum(0.299 * r + 0.587 * g + 0.114 * b for r, g, b, _ in px) / len(px)


def encode(im):
    """返回 (data_url, 字节数, 格式名)。webp 反而更大时退回 png。"""
    bp = io.BytesIO()
    im.save(bp, "PNG", optimize=True, compress_level=9)
    png = bp.getvalue()
    if USE_WEBP:
        bw = io.BytesIO()
        im.save(bw, "WEBP", quality=WEBP_QUALITY, method=6, exact=True)
        webp = bw.getvalue()
        if len(webp) < len(png):
            return "data:image/webp;base64," + base64.b64encode(webp).decode("ascii"), len(webp), "webp"
    return "data:image/png;base64," + base64.b64encode(png).decode("ascii"), len(png), "png"


items, report = [], []
for f in glob.glob(os.path.join(SRC, "*.png")):
    stem = os.path.splitext(os.path.basename(f))[0]
    m = PATTERN.match(stem)
    if not m:
        continue

    im = Image.open(f).convert("RGBA")
    orig = im.size
    if max(im.size) > MAX_DIM:
        im = downscale(im, MAX_DIM)

    luma = mean_luma(im)
    src, nbytes, fmt = encode(im)

    items.append({
        "name": stem,
        "base": m.group("base"),
        "variant": m.group("variant"),
        "light": luma > LIGHT_THRESHOLD,
        "src": src,
    })
    report.append((m.group("variant"), stem, orig, im.size, nbytes / 1024,
                   os.path.getsize(f) / 1024, luma, fmt))

order = {it["name"]: (it["base"], it["variant"]) for it in items}
items.sort(key=lambda it: order[it["name"]])
report.sort(key=lambda r: order[r[1]])

with open(OUT, "w", encoding="utf-8") as fh:
    fh.write("// Auto-generated by gen_logos.py - do not edit by hand\n")
    fh.write("const LOGO_DATA = ")
    json.dump(items, fh, ensure_ascii=False)
    fh.write(";\n")

print("numpy=%s  webp=%s  MAX_DIM=%d  light>%d" % (
    HAVE_NUMPY, USE_WEBP, MAX_DIM, LIGHT_THRESHOLD))
print("wrote %s  (%d logos, %.0f KB)" % (OUT, len(items), os.path.getsize(OUT) / 1024))
for variant, name, orig, now, kb, disk, luma, fmt in report:
    note = "" if orig == now else "  <- %dx%d" % orig
    print("  v%s %-14s %4dx%-4d %4s %7.1fKB (disk %6.1fKB) lum=%5.1f %s%s" % (
        variant, json.dumps(name, ensure_ascii=True), now[0], now[1], fmt, kb, disk, luma,
        "LIGHT" if luma > LIGHT_THRESHOLD else "dark ", note))
